#!/usr/bin/env python3
"""Write the dre: vocabulary as Turtle, RDF/XML, JSON-LD and HTML.

The terms below are the single source. Run this after editing them and commit
the four generated files beside it:

    python3 deploy/amira/vocabularies/build_dre_vocabulary.py

nginx serves the files at /ontology/dre (see nginx-dre-vocabulary-location.conf),
the entrypoint imports dre.rdf into a fresh Omeka (dre.json), and
MongoDB2OmekaS keeps a copy of dre.ttl for Admin -> Vocabularies -> Update.

The namespace is a hash namespace on AMIRA's own domain, so one document
answers for every term. Each term is declared owl:equivalentProperty to its
former http://am-digital.org/ontology/dre/ IRI, which has never resolved but
was published in the first Linked Data dumps.
"""
import json
from html import escape as html_escape
from pathlib import Path
from xml.sax.saxutils import escape as xml_escape, quoteattr

ONTOLOGY = "https://data.africamultiple.uni-bayreuth.de/ontology/dre"
NAMESPACE = ONTOLOGY + "#"
FORMER_NAMESPACE = "http://am-digital.org/ontology/dre/"
MODIFIED = "2026-10-15"

TITLE = "DRE — Africa Multiple Digital Research Environment vocabulary"
DESCRIPTION = (
    "Properties the Africa Multiple Digital Research Environment adds to "
    "Dublin Core, BIBO, FOAF and the other vocabularies of AMIRA, the Africa "
    "Multiple Interactive Research Atlas: identifiers and links into the "
    "University of Bayreuth's systems, provenance of machine-generated values, "
    "and the internal fields that keep AMIRA in sync with its source database."
)
PUBLISHER = "http://www.wikidata.org/entity/Q141717295"
PUBLISHER_NAME = "Africa Multiple Cluster of Excellence, University of Bayreuth"
LICENCE = "https://creativecommons.org/publicdomain/zero/1.0/"
DATASET = "https://data.africamultiple.uni-bayreuth.de/linked-data/void"

# (local name, label, comment, deprecated)
TERMS = [
    ("id", "DRE ID",
     "Internal identifier used by the Digital Research Environment.", False),
    ("security", "Security level",
     "Data sensitivity level (DSL1-DSL5) defining access restrictions.", False),
    ("bitstream", "Bitstream",
     "Filename of the associated digital object or file.", False),
    ("mongoId", "MongoDB ID",
     "Original MongoDB ObjectId, used for sync reconciliation. Should be private.",
     False),
    ("rdspaceHandle", "RDSpace Handle",
     "Persistent handle URL from the RDSpace repository at the University of "
     "Bayreuth (rdspace.uni-bayreuth.de).", False),
    ("collectionUrl", "Collection URL",
     "Permalink to the item in the University of Bayreuth Digital Collections "
     "(DSpace) platform at collections.uni-bayreuth.de. A different system from "
     "RDSpace.", False),
    ("generatedBy", "Generated by",
     "The agent — typically an AI model — that automatically generated this "
     "value (e.g. a machine-produced transcript, description or translation). "
     "Used as a value annotation pointing to the generating tool's authority "
     "record, distinguishing machine-generated content from a human contributor "
     "role.", False),
    ("series", "Series",
     "The bibliographic series (and series number) a publication belongs to, "
     "e.g. 'BIGSASworks!; 23'. Kept distinct from dcterms:isPartOf, which holds "
     "the publication's single immediate container (its journal or book) — a "
     "monograph or working paper with no such container uses its primary series "
     "as the isPartOf container instead, and only a secondary series statement "
     "lands here.", False),
    ("wisskiUrl", "WissKI URL",
     "Navigate URL to the item in the WissKI knowledge base at the University "
     "of Bayreuth. No longer populated: WissKI links were retired from the sync.",
     True),
]

PREFIXES = {
    "rdf": "http://www.w3.org/1999/02/22-rdf-syntax-ns#",
    "rdfs": "http://www.w3.org/2000/01/rdf-schema#",
    "owl": "http://www.w3.org/2002/07/owl#",
    "xsd": "http://www.w3.org/2001/XMLSchema#",
    "dcterms": "http://purl.org/dc/terms/",
    "vann": "http://purl.org/vocab/vann/",
    "dre": NAMESPACE,
}


def turtle_string(value):
    escaped = value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return f'"{escaped}"'


def build_turtle():
    lines = [f"@prefix {p}: <{iri}> ." for p, iri in PREFIXES.items()]
    lines += [
        "",
        f"<{ONTOLOGY}>",
        "    a owl:Ontology ;",
        '    rdfs:label "DRE"@en ;',
        f"    dcterms:title {turtle_string(TITLE)}@en ;",
        f"    rdfs:comment {turtle_string(DESCRIPTION)}@en ;",
        f"    dcterms:publisher <{PUBLISHER}> ;",
        f"    dcterms:license <{LICENCE}> ;",
        f'    dcterms:modified "{MODIFIED}"^^xsd:date ;',
        '    vann:preferredNamespacePrefix "dre" ;',
        f'    vann:preferredNamespaceUri "{NAMESPACE}" ;',
        f"    owl:priorVersion <{FORMER_NAMESPACE}> ;",
        f"    rdfs:seeAlso <{DATASET}> .",
    ]
    for name, label, comment, deprecated in TERMS:
        lines += [
            "",
            f"dre:{name}",
            "    a rdf:Property ;",
            f"    rdfs:label {turtle_string(label)}@en ;",
            f"    rdfs:comment {turtle_string(comment)}@en ;",
            f"    rdfs:isDefinedBy <{ONTOLOGY}> ;",
        ]
        if deprecated:
            lines.append("    owl:deprecated true ;")
        lines.append(f"    owl:equivalentProperty <{FORMER_NAMESPACE}{name}> .")
    return "\n".join(lines) + "\n"


def build_rdfxml():
    ns = "".join(f'\n    xmlns:{p}="{iri}"' for p, iri in PREFIXES.items())
    lang = 'xml:lang="en"'
    out = [f'<?xml version="1.0" encoding="UTF-8"?>\n<rdf:RDF{ns}>', ""]
    out += [
        f"  <owl:Ontology rdf:about={quoteattr(ONTOLOGY)}>",
        f"    <rdfs:label {lang}>DRE</rdfs:label>",
        f"    <dcterms:title {lang}>{xml_escape(TITLE)}</dcterms:title>",
        f"    <rdfs:comment {lang}>{xml_escape(DESCRIPTION)}</rdfs:comment>",
        f"    <dcterms:publisher rdf:resource={quoteattr(PUBLISHER)}/>",
        f"    <dcterms:license rdf:resource={quoteattr(LICENCE)}/>",
        f'    <dcterms:modified rdf:datatype="{PREFIXES["xsd"]}date">{MODIFIED}</dcterms:modified>',
        "    <vann:preferredNamespacePrefix>dre</vann:preferredNamespacePrefix>",
        f"    <vann:preferredNamespaceUri>{xml_escape(NAMESPACE)}</vann:preferredNamespaceUri>",
        f"    <owl:priorVersion rdf:resource={quoteattr(FORMER_NAMESPACE)}/>",
        f"    <rdfs:seeAlso rdf:resource={quoteattr(DATASET)}/>",
        "  </owl:Ontology>",
    ]
    for name, label, comment, deprecated in TERMS:
        out += [
            "",
            f"  <rdf:Property rdf:about={quoteattr(NAMESPACE + name)}>",
            f"    <rdfs:label {lang}>{xml_escape(label)}</rdfs:label>",
            f"    <rdfs:comment {lang}>{xml_escape(comment)}</rdfs:comment>",
            f"    <rdfs:isDefinedBy rdf:resource={quoteattr(ONTOLOGY)}/>",
        ]
        if deprecated:
            out.append(f'    <owl:deprecated rdf:datatype="{PREFIXES["xsd"]}boolean">true</owl:deprecated>')
        out += [
            f"    <owl:equivalentProperty rdf:resource={quoteattr(FORMER_NAMESPACE + name)}/>",
            "  </rdf:Property>",
        ]
    out += ["", "</rdf:RDF>"]
    return "\n".join(out) + "\n"


def build_jsonld():
    def en(value):
        return {"@value": value, "@language": "en"}

    graph = [{
        "@id": ONTOLOGY,
        "@type": "owl:Ontology",
        "rdfs:label": en("DRE"),
        "dcterms:title": en(TITLE),
        "rdfs:comment": en(DESCRIPTION),
        "dcterms:publisher": {"@id": PUBLISHER},
        "dcterms:license": {"@id": LICENCE},
        "dcterms:modified": {"@value": MODIFIED, "@type": "xsd:date"},
        "vann:preferredNamespacePrefix": "dre",
        "vann:preferredNamespaceUri": NAMESPACE,
        "owl:priorVersion": {"@id": FORMER_NAMESPACE},
        "rdfs:seeAlso": {"@id": DATASET},
    }]
    for name, label, comment, deprecated in TERMS:
        term = {
            "@id": f"dre:{name}",
            "@type": "rdf:Property",
            "rdfs:label": en(label),
            "rdfs:comment": en(comment),
            "rdfs:isDefinedBy": {"@id": ONTOLOGY},
        }
        if deprecated:
            term["owl:deprecated"] = True
        term["owl:equivalentProperty"] = {"@id": FORMER_NAMESPACE + name}
        graph.append(term)
    return json.dumps({"@context": PREFIXES, "@graph": graph},
                      ensure_ascii=False, indent=2) + "\n"


HTML_STYLE = """
  :root { color-scheme: light dark; --bg: #fff; --fg: #1d1d1f; --muted: #5f6368;
    --rule: #dadce0; --accent: #8a1538; --code: #f4f4f5; }
  @media (prefers-color-scheme: dark) {
    :root { --bg: #121212; --fg: #e8e8ea; --muted: #a0a3a8; --rule: #333;
      --accent: #e8849e; --code: #1e1e20; }
  }
  * { box-sizing: border-box; }
  body { margin: 0; background: var(--bg); color: var(--fg);
    font: 16px/1.6 system-ui, -apple-system, "Segoe UI", sans-serif; }
  main { max-width: 52rem; margin: 0 auto; padding: 2.5rem 1rem 4rem; }
  h1 { font-size: 1.75rem; line-height: 1.25; margin: 0 0 .5rem; }
  h2 { font-size: 1.25rem; margin: 2.5rem 0 1rem; }
  h3 { font-size: 1.1rem; margin: 0 0 .25rem; }
  a { color: var(--accent); }
  code { background: var(--code); padding: .1em .3em; border-radius: 3px;
    font-size: .9em; overflow-wrap: anywhere; }
  .lead { color: var(--muted); margin: 0 0 1.5rem; }
  dl.meta { display: grid; grid-template-columns: max-content 1fr; gap: .25rem 1rem; margin: 0; }
  dl.meta dt { color: var(--muted); }
  dl.meta dd { margin: 0; min-width: 0; }
  section.term { border-top: 1px solid var(--rule); padding: 1.25rem 0; scroll-margin-top: 1rem; }
  section.term:target { background: var(--code); padding-left: .75rem; padding-right: .75rem; }
  .badge { font-size: .75rem; border: 1px solid var(--muted); color: var(--muted);
    border-radius: 999px; padding: 0 .5rem; margin-left: .5rem; vertical-align: middle; }
  .iri { color: var(--muted); font-size: .9rem; margin: 0 0 .5rem; }
  .term p { margin: .25rem 0; }
  @media (max-width: 30rem) { dl.meta { grid-template-columns: 1fr; } dl.meta dd { margin-bottom: .5rem; } }
"""


def build_html():
    h = html_escape
    formats = [("dre.ttl", "text/turtle", "Turtle"),
               ("dre.rdf", "application/rdf+xml", "RDF/XML"),
               ("dre.jsonld", "application/ld+json", "JSON-LD")]
    alternates = "\n".join(
        f'<link rel="alternate" type="{t}" href="{f}" title="{n}">' for f, t, n in formats)
    format_links = " · ".join(f'<a href="{f}" type="{t}">{n}</a>' for f, t, n in formats)
    toc = ", ".join(f'<a href="#{n}"><code>dre:{n}</code></a>' for n, *_ in TERMS)
    sections = []
    for name, label, comment, deprecated in TERMS:
        badge = '<span class="badge">deprecated</span>' if deprecated else ""
        sections.append(f"""
<section class="term" id="{name}">
  <h3>{h(label)} <code>dre:{name}</code>{badge}</h3>
  <p class="iri">{h(NAMESPACE + name)}</p>
  <p>{h(comment)}</p>
  <p>Equivalent to the former IRI <code>{h(FORMER_NAMESPACE + name)}</code>.</p>
</section>""")
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>DRE vocabulary</title>
<meta name="description" content="{h(DESCRIPTION)}">
<link rel="canonical" href="{ONTOLOGY}">
{alternates}
<style>{HTML_STYLE}</style>
</head>
<body>
<main>
<h1>{h(TITLE)}</h1>
<p class="lead">{h(DESCRIPTION)}</p>
<dl class="meta">
  <dt>Namespace</dt><dd><code>{h(NAMESPACE)}</code></dd>
  <dt>Prefix</dt><dd><code>dre</code></dd>
  <dt>Formats</dt><dd>{format_links}</dd>
  <dt>Publisher</dt><dd><a href="{PUBLISHER}">{h(PUBLISHER_NAME)}</a></dd>
  <dt>Licence</dt><dd><a href="{LICENCE}">CC0 1.0</a></dd>
  <dt>Modified</dt><dd>{MODIFIED}</dd>
  <dt>Used in</dt><dd><a href="{DATASET}">AMIRA's Linked Data</a></dd>
</dl>

<h2>Former namespace</h2>
<p>Until {MODIFIED} these terms were published under <code>{h(FORMER_NAMESPACE)}</code>,
which never resolved. Each term here is declared <code>owl:equivalentProperty</code> to
its former IRI, so data loaded from earlier dumps can still be joined with current data.</p>

<h2>Terms</h2>
<p>{toc}</p>
{"".join(sections)}
</main>
</body>
</html>
"""


def main():
    here = Path(__file__).resolve().parent
    outputs = {
        "dre.ttl": build_turtle(),
        "dre.rdf": build_rdfxml(),
        "dre.jsonld": build_jsonld(),
        "dre.html": build_html(),
    }
    for name, content in outputs.items():
        (here / name).write_text(content, encoding="utf-8")
        print(f"wrote {name}")


if __name__ == "__main__":
    main()
